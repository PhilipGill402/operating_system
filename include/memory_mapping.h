#ifndef INCLUDE_MEMORY_MAPPING_H_
#define INCLUDE_MEMORY_MAPPING_H_

#define KERNEL_BASE 0xC0000000

#define KERNEL_STACK_BOTTOM 0xC1000000
#define KERNEL_STACK_TOP    0xC1100000
#define KERNEL_STACK_SIZE   (KERNEL_STACK_TOP - KERNEL_STACK_BOTTOM)

#define MULTIBOOT_VIRT_START    0xC1100000
#define MULTIBOOT_VIRT_END      0xC2000000

#define MULTIBOOT_INFO_VIRT     0xC1100000
#define MULTIBOOT_MMAP_VIRT     0xC1110000
#define MODS_TABLE_VIRT         0xC1120000
#define INITRD_VIRT_ADDRESS     0xC1200000
#define INITRD_VIRT_END         0xC2000000

#define KHEAP_START 0xC2000000
#define KHEAP_END   0xC6000000

#define KERNEL_VIRT_START 0xC6000000
#define KERNEL_VIRT_END   0xD0000000

#define FRAMEBUFFER_VIRT 0xD0000000

#define TEMP_MAP_BASE 0xF0000000

#define TEMP_MAP_0    (TEMP_MAP_BASE + 0x0000)
#define TEMP_MAP_1    (TEMP_MAP_BASE + 0x1000)
#define TEMP_MAP_2    (TEMP_MAP_BASE + 0x2000)
#define TEMP_MAP_3    (TEMP_MAP_BASE + 0x3000)
#define TEMP_MAP_4    (TEMP_MAP_BASE + 0x4000)
#define TEMP_MAP_5    (TEMP_MAP_BASE + 0x5000)

#define TEMP_PD_INDEX (TEMP_MAP_BASE >> 22)

#endif
