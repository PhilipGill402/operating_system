#ifndef ARCH_RISCV64_INCLUDE_MEMORY_MEMORY_MAP_H_
#define ARCH_RISCV64_INCLUDE_MEMORY_MEMORY_MAP_H_

/* Sv39 canonical split */
#define USER_VIRT_START        0x0000000000000000ULL
#define USER_VIRT_END          0x0000003FFFFFFFFFULL

#define KERNEL_VIRT_START      0xFFFFFFC000000000ULL
#define KERNEL_VIRT_END        0xFFFFFFFFFFFFFFFFULL

/* Kernel image */
#define KERNEL_BASE            0xFFFFFFC000000000ULL
#define KERNEL_REGION_SIZE     0x0000000040000000ULL   /* 1 GiB */
#define KERNEL_REGION_END      (KERNEL_BASE + KERNEL_REGION_SIZE)
#define KERNEL_OFFSET          (KERNEL_BASE - 0x80000000ULL)

/* Kernel heap */
#define KHEAP_START            0xFFFFFFC040000000ULL
#define KHEAP_SIZE             0x0000000040000000ULL   /* 1 GiB reserved VA */
#define KHEAP_INITIAL_SIZE     (4ULL * 1024 * 1024)
#define KHEAP_END              (KHEAP_START + KHEAP_SIZE)

/* Temporary physical mappings */
#define TEMP_MAP_BASE          0xFFFFFFC080000000ULL
#define NUM_TEMP_REGIONS       8
#define TEMP_MAP_SIZE          (NUM_TEMP_REGIONS * PAGE_SIZE)
#define TEMP_MAP_END           (TEMP_MAP_BASE + TEMP_MAP_SIZE)

/* Direct physical-memory map */
#define PHYS_MAP_BASE          0xFFFFFFD000000000ULL
#define PHYS_MAP_SIZE          0x0000001000000000ULL
#define PHYS_MAP_END           (PHYS_MAP_BASE + PHYS_MAP_SIZE)

/* Kernel stacks */
#define KSTACK_REGION_START    0xFFFFFFE000000000ULL
#define KSTACK_REGION_SIZE     0x0000000100000000ULL
#define KSTACK_SIZE            (16ULL * 1024)
#define KSTACK_REGION_END      (KSTACK_REGION_START + KSTACK_REGION_SIZE)

/* User layout */
#define USER_IMAGE_START       0x0000000000400000ULL

#define USER_HEAP_START        0x0000000010000000ULL
#define USER_HEAP_END          0x0000000020000000ULL

#define USER_STACK_BOTTOM      0x0000003FFF000000ULL
#define USER_STACK_TOP         0x0000003FFFFFFFF0ULL

#endif
